#!/usr/bin/env node
/**
 * audit-crm-ux-reality.mjs — RO-1 "live reality" precondition table for the
 * PIFH CRM (Road to Ten). READ-ONLY. Counts + config only, never record
 * values and never PII. The service-role key is read from the env or
 * apps/crm/.env.local / .env (same pick-up as scripts/e2e/dump-prod-fixture-shapes.mjs)
 * and is never printed.
 *
 * Sources
 *   1. scripts/e2e/fixture-shapes.json — the read-only prod CONFIG snapshot
 *      (crm_modules / crm_fields / crm_views / crm_layouts / crm_feature_flags /
 *      crm_status_vocabulary + aggregate counts) written by
 *      scripts/e2e/dump-prod-fixture-shapes.mjs. `--refresh` re-runs that dump first.
 *   2. A few live COUNT-only queries the snapshot lacks (crm_advisors,
 *      crm_records 'advisors', public.advisors, status group counts for
 *      contacts/leads/members via the execute_report_aggregation RPC — arrays
 *      passed as jsonb, the working call shape). `--offline` skips them.
 *
 * Lane bucketing reuses apps/crm/src/lib/crm/status-lanes.ts (statusLane) and
 * the sidebar roster reuses apps/crm/src/lib/crm/nav-profile.ts
 * (navigableModules) — loaded through tsx so there is no second copy of either
 * rule. The script re-execs itself under `node --import tsx` when needed.
 *
 *   node scripts/audit-crm-ux-reality.mjs            # print the markdown table
 *   node scripts/audit-crm-ux-reality.mjs --write    # also replace the RO-1 block in docs/ux/live-reality-2026-08-22.md
 *   node scripts/audit-crm-ux-reality.mjs --offline  # snapshot only (no live queries)
 *   node scripts/audit-crm-ux-reality.mjs --refresh  # re-run the prod config dump first (read-only)
 */
import { createClient } from '@supabase/supabase-js';
import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(HERE, '..');
const ORG_ID = '00000000-0000-0000-0000-000000000001';
const SNAPSHOT = path.join(REPO_ROOT, 'scripts/e2e/fixture-shapes.json');
const DUMP_SCRIPT = path.join(REPO_ROOT, 'scripts/e2e/dump-prod-fixture-shapes.mjs');
const DOC = path.join(REPO_ROOT, 'docs/ux/live-reality-2026-08-22.md');
const MARK_BEGIN = '<!-- RO-1:begin (generated by scripts/audit-crm-ux-reality.mjs) -->';
const MARK_END = '<!-- RO-1:end -->';
const PEOPLE_MODULES = ['contacts', 'leads', 'members'];

const args = new Set(process.argv.slice(2));
const OFFLINE = args.has('--offline');
const WRITE = args.has('--write');
const REFRESH = args.has('--refresh');

// --- re-exec under tsx so the CRM's own TS rules can be imported ------------
if (!process.env.AUDIT_UX_REALITY_TSX) {
  const r = spawnSync(process.execPath, ['--import', 'tsx', ...process.argv.slice(1)], {
    stdio: 'inherit',
    cwd: REPO_ROOT,
    env: {
      ...process.env,
      AUDIT_UX_REALITY_TSX: '1',
      TSX_TSCONFIG_PATH: path.join(REPO_ROOT, 'apps/crm/tsconfig.json'),
      NODE_OPTIONS: [process.env.NODE_OPTIONS, '--no-deprecation'].filter(Boolean).join(' '),
    },
  });
  if (r.error || r.status !== 0) {
    console.error(`tsx re-exec failed (${r.error?.message ?? `exit ${r.status}`}); continuing without the TS rule imports`);
    process.env.AUDIT_UX_REALITY_TSX = 'fallback';
  } else {
    process.exit(0);
  }
}

let statusLane = null;
let laneIds = null;
let navigableModules = null;
if (process.env.AUDIT_UX_REALITY_TSX === '1') {
  const lanes = await import('../apps/crm/src/lib/crm/status-lanes.ts');
  statusLane = lanes.statusLane;
  laneIds = lanes.STATUS_LANE_IDS;
  ({ navigableModules } = await import('../apps/crm/src/lib/crm/nav-profile.ts'));
}

// --- snapshot ---------------------------------------------------------------
if (REFRESH) {
  const r = spawnSync(process.execPath, [DUMP_SCRIPT], { stdio: 'inherit', cwd: REPO_ROOT });
  if (r.status !== 0) { console.error('dump-prod-fixture-shapes.mjs failed'); process.exit(1); }
}
if (!existsSync(SNAPSHOT)) { console.error(`missing ${SNAPSHOT}; run scripts/e2e/dump-prod-fixture-shapes.mjs`); process.exit(2); }
const snap = JSON.parse(readFileSync(SNAPSHOT, 'utf8'));
const modules = snap.modules ?? [];
const fields = snap.fields ?? [];
const views = snap.views ?? [];
const layouts = snap.layouts ?? [];
const flags = snap.feature_flags ?? [];
const vocab = snap.status_vocabulary ?? [];
const fieldsByModule = new Map();
for (const f of fields) { if (!fieldsByModule.has(f.module_key)) fieldsByModule.set(f.module_key, []); fieldsByModule.get(f.module_key).push(f); }
const fieldOf = (mod, key) => (fieldsByModule.get(mod) ?? []).find((f) => f.key === key) ?? null;
const optionCount = (f) => (Array.isArray(f?.options) ? f.options.length : 0);

// --- live counts (read-only) ------------------------------------------------
function fromEnvFile(file, key) {
  if (!existsSync(file)) return null;
  const line = readFileSync(file, 'utf8').split('\n').find((l) => l.startsWith(`${key}=`));
  return line ? line.slice(key.length + 1).trim().replace(/^["']|["']$/g, '') : null;
}
const envFiles = [path.join(REPO_ROOT, 'apps/crm/.env.local'), path.join(REPO_ROOT, '.env')];
const pick = (key) => process.env[key] || envFiles.map((f) => fromEnvFile(f, key)).find(Boolean) || null;

const live = { ok: false, note: 'offline (snapshot only)', counts: {}, statusGroups: {} };
if (!OFFLINE) {
  const URL = pick('NEXT_PUBLIC_SUPABASE_URL');
  const KEY = pick('SUPABASE_SERVICE_ROLE_KEY');
  if (!URL || !KEY) {
    live.note = 'no NEXT_PUBLIC_SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY found — snapshot only';
  } else {
    const sb = createClient(URL, KEY, { auth: { persistSession: false, autoRefreshToken: false } });
    const host = (() => { try { return new globalThis.URL(URL).host; } catch { return URL; } })();
    async function countRows(table, filter) {
      let q = sb.from(table).select('id', { count: 'exact', head: true });
      for (const [k, v] of Object.entries(filter ?? {})) q = v === null ? q.is(k, null) : q.eq(k, v);
      const { count, error } = await q;
      return error ? `error: ${error.message}` : count;
    }
    const modId = (key) => modules.find((m) => m.key === key)?.prod_id ?? null;
    try {
      live.counts.crm_advisors_total = await countRows('crm_advisors', {});
      live.counts.crm_advisors_active = await countRows('crm_advisors', { is_active: true });
      live.counts.crm_records_advisors = modId('advisors')
        ? await countRows('crm_records', { org_id: ORG_ID, module_id: modId('advisors'), deleted_at: null })
        : 'advisors module missing';
      live.counts.public_advisors = await countRows('advisors', { organization_id: ORG_ID });
      live.counts.public_advisors_active = await countRows('advisors', { organization_id: ORG_ID, is_active: true });
      live.counts.public_advisors_not_deleted = await countRows('advisors', { organization_id: ORG_ID, deleted_at: null });
      for (const key of PEOPLE_MODULES) {
        const id = modId(key);
        if (!id) { live.statusGroups[key] = { error: 'module missing' }; continue; }
        // Same RPC the status-values route / people queue use; jsonb params are
        // passed as real arrays (the JSON.stringify'd form 500s — Wave-0 defect).
        const { data, error } = await sb.rpc('execute_report_aggregation', {
          p_org_id: ORG_ID,
          p_table: 'crm_records',
          p_org_column: 'org_id',
          p_module_id: id,
          p_filters: [{ field: 'deleted_at', operator: 'is_null' }],
          p_filter_logic: 'and',
          p_grouping: [{ field: 'status' }],
          p_aggregations: [{ field: 'id', function: 'count' }],
          p_sorting: [{ column: 'count_id', direction: 'desc' }],
          p_limit: 500,
          p_offset: 0,
          p_include_downline: false,
        });
        if (error) { live.statusGroups[key] = { error: error.message }; continue; }
        const rows = Array.isArray(data?.rows) ? data.rows : [];
        live.statusGroups[key] = { rows: rows.map((r) => ({ status: typeof r.status === 'string' ? r.status : null, count: Number(r.count_id ?? 0) || 0 })) };
      }
      live.ok = true;
      live.note = `live counts from ${host} at ${new Date().toISOString()}`;
    } catch (e) {
      live.note = `live queries failed: ${e?.message ?? e}`;
    }
  }
}

// --- rows -------------------------------------------------------------------
const rows = [];
const add = (n, precondition, verdict, value) => rows.push({ n, precondition, verdict, value });
const md = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const fmt = (n) => (typeof n === 'number' ? n.toLocaleString('en-US') : String(n));

// (1) layouts
for (const key of PEOPLE_MODULES) {
  const ls = layouts.filter((l) => l.module_key === key);
  const defaults = ls.filter((l) => l.is_default);
  const d = defaults[0];
  const sections = d?.config?.sections ?? [];
  const hero = sections.filter((s) => s.variant === 'hero').map((s) => s.key);
  const collapsed = sections.filter((s) => s.collapsed).map((s) => s.key);
  const open = sections.filter((s) => !s.collapsed).map((s) => s.key);
  let verdict = defaults.length === 1 && hero.length === 1 ? 'PASS' : 'FAIL';
  let extra = '';
  if (key === 'contacts') {
    const need = ['management', 'insurance', 'identifiers'];
    const bad = need.filter((k) => sections.find((s) => s.key === k)?.collapsed !== false);
    extra = bad.length ? ` — ${bad.join('/')} NOT collapsed=false` : ' — management/insurance/identifiers collapsed=false';
    if (bad.length) verdict = 'FAIL';
  }
  add('1', `crm_layouts ${key}: one is_default row, one hero section, collapsed set`,
    verdict,
    `${ls.length} row(s), ${defaults.length} default ("${d?.name ?? '—'}", ${sections.length} sections); hero=${hero.join(',') || 'none'}; open: ${open.join(', ') || '—'}; collapsed(${collapsed.length}): ${collapsed.join(', ') || '—'}${extra}`);
}
{
  const others = modules.filter((m) => !PEOPLE_MODULES.includes(m.key)).map((m) => {
    const ls = layouts.filter((l) => l.module_key === m.key);
    const d = ls.find((l) => l.is_default);
    const hero = (d?.config?.sections ?? []).some((s) => s.variant === 'hero');
    return `${m.key}: ${ls.length} layout(s)${d ? `, default "${d.name}" hero=${hero ? 'yes' : 'no'}` : ', no default'}`;
  });
  add('1', 'crm_layouts other modules (non-people; fail-open per DynamicRecordForm)', 'INFO', others.join('; '));
}

// (2) views
for (const m of modules) {
  const vs = views.filter((v) => v.module_key === m.key);
  const defaults = vs.filter((v) => v.is_default);
  if (!vs.length) { add('2', `crm_views ${m.key} default`, PEOPLE_MODULES.includes(m.key) ? 'FAIL' : 'INFO', 'no views'); continue; }
  const d = defaults[0];
  const sort = (d?.sort ?? []).map((s) => `${s.field} ${s.direction}`).join(', ') || 'none';
  add('2', `crm_views ${m.key} default view: sort + columns`,
    defaults.length === 1 ? (PEOPLE_MODULES.includes(m.key) ? 'PASS' : 'INFO') : 'FAIL',
    `${vs.length} view(s), ${defaults.length} default ("${d?.name ?? '—'}" ${d?.prod_id?.slice(0, 8) ?? ''}); sort=${sort}; columns=${(d?.columns ?? []).join(', ')}`);
}

// (3) fields
{
  const mf = ['plan_name', 'effective_date', 'product', 'sharing_effective_date'].map((k) => {
    const f = fieldOf('members', k);
    return `${k}: ${f ? `${f.type} (section ${f.section}, label "${f.label}")` : 'MISSING'}`;
  });
  add('3', 'members fields plan_name / effective_date / product present?',
    fieldOf('members', 'plan_name') && fieldOf('members', 'effective_date') ? 'PASS' : 'FAIL',
    `${mf.join('; ')} — LS-4 must read plan_name (members carry no product field)`);
  const cp = fieldOf('contacts', 'product');
  const lp = fieldOf('leads', 'product_type');
  const cpt = fieldOf('contacts', 'product_type');
  add('3', 'contacts.product + leads.product_type: type + option counts (DE-1)',
    cp && lp ? 'PASS' : 'FAIL',
    `contacts.product: ${cp ? `${cp.type}, ${optionCount(cp)} options, label "${cp.label}", section ${cp.section}` : 'MISSING'}; leads.product_type: ${lp ? `${lp.type}, ${optionCount(lp)} options, label "${lp.label}", section ${lp.section}` : 'MISSING'}; contacts.product_type (second field): ${cpt ? `${cpt.type}, ${optionCount(cpt)} options, label "${cpt.label}"` : 'MISSING'}`);
  const hp = PEOPLE_MODULES.map((k) => { const f = fieldOf(k, 'health_insurance_plan_name'); return `${k}: ${f ? `${f.type}/${optionCount(f)} options` : 'MISSING'}`; });
  add('3', 'health_insurance_plan_name type (DE-2/D4 free text + suggestions)',
    PEOPLE_MODULES.every((k) => fieldOf(k, 'health_insurance_plan_name')?.type === 'text') ? 'PASS' : 'INFO',
    hp.join('; '));
  const prod = [['contacts', 'producer_name'], ['contacts', 'producer_record_id'], ['leads', 'producer'], ['members', 'advisor_name']]
    .map(([m, k]) => { const f = fieldOf(m, k); return `${m}.${k}: ${f ? `${f.type} (${f.section})` : 'MISSING'}`; });
  add('3', 'producer display keys (DE-3 / D5 adjusted)', 'INFO', prod.join('; '));
}

// (4) advisor stores
{
  const c = live.ok ? live.counts : {};
  const agg = snap.aggregates ?? {};
  const v = live.ok
    ? `crm_advisors: ${fmt(c.crm_advisors_total)} total / ${fmt(c.crm_advisors_active)} active; crm_records 'advisors' (not deleted): ${fmt(c.crm_records_advisors)}; public.advisors (org-scoped): ${fmt(c.public_advisors)} total / ${fmt(c.public_advisors_active)} is_active / ${fmt(c.public_advisors_not_deleted)} not deleted`
    : `snapshot: crm_advisors active ${fmt(agg.crm_advisors_active ?? '?')}; crm_records 'advisors' ${fmt(agg.crm_records_by_module?.advisors ?? '?')}; public.advisors ${fmt(agg.advisors_rows ?? '?')} (${live.note})`;
  add('4', 'advisor store counts (crm_advisors / crm_records advisors / public.advisors)', 'PASS', `${v} — picker source of truth = public.advisors (D5 adjusted)`);
}

// (5) flags
{
  const f = (key, scope) => flags.find((x) => x.flag_key === key && x.scope === scope);
  const l2g = f('crm.layout.v2', 'global'); const l2o = f('crm.layout.v2', 'pifh'); const ns = f('crm.nav.simple', 'pifh'); const nsg = f('crm.nav.simple', 'global');
  add('5', 'crm.layout.v2 global + org; crm.nav.simple org',
    l2g?.enabled === true && ns && ns.enabled === false ? 'PASS' : 'FAIL',
    `crm.layout.v2 global=${l2g ? l2g.enabled : 'no row'}, PIFH=${l2o ? l2o.enabled : 'no row (inherits global)'}; crm.nav.simple PIFH=${ns ? ns.enabled : 'no row'}, global=${nsg ? nsg.enabled : 'no row'} → full shell`);
}

// (6) modules + roster
{
  const navMods = modules.map((m) => ({ ...m, field_count: (fieldsByModule.get(m.key) ?? []).length }));
  const list = navMods.map((m) => `${m.key} ${m.is_enabled ? 'ON' : 'off'} (${m.field_count} fields, ${fmt(snap.aggregates?.crm_records_by_module?.[m.key] ?? '?')} records)`);
  const roster = navigableModules
    ? navigableModules(navMods).map((m) => m.key)
    : navMods.filter((m) => m.is_enabled !== false && m.field_count > 0).map((m) => m.key);
  const advisorsOn = roster.includes('advisors');
  add('6', 'crm_modules enabled + field counts → sidebar roster',
    roster.includes('contacts') && roster.includes('leads') && roster.includes('members') && !roster.includes('deals') && !roster.includes('prospects') ? 'PASS' : 'FAIL',
    `${list.join('; ')} → navigable${navigableModules ? ' (nav-profile.navigableModules)' : ''}: Sales Pipeline ${roster.filter((k) => k !== 'advisors').join(', ')}; People Management → Advisors ${advisorsOn ? 'shown' : 'hidden'}; deals/prospects ${roster.includes('deals') || roster.includes('prospects') ? 'NAVIGABLE' : 'not navigable (NV-2 redirect)'}`);
}

// (7) vocabulary + lanes
for (const key of PEOPLE_MODULES) {
  const allowed = vocab.find((v) => v.module_key === key)?.statuses ?? [];
  const g = live.statusGroups[key];
  let laneText;
  let verdict = allowed.length ? 'PASS' : 'FAIL';
  if (!live.ok || !g || g.error) {
    laneText = g?.error ? `lane counts unavailable (${g.error})` : `lane counts unavailable (${live.note})`;
    verdict = allowed.length ? 'INFO' : 'FAIL';
  } else {
    const total = g.rows.reduce((a, r) => a + r.count, 0);
    const blank = g.rows.filter((r) => !r.status || !r.status.trim()).reduce((a, r) => a + r.count, 0);
    const distinct = g.rows.filter((r) => r.status && r.status.trim()).length;
    const allowedSet = new Set(allowed.map((s) => s.toLowerCase()));
    const inVocab = g.rows.filter((r) => r.status && allowedSet.has(r.status.trim().toLowerCase())).reduce((a, r) => a + r.count, 0);
    let lanes = '';
    if (statusLane && laneIds) {
      const byLane = Object.fromEntries(laneIds.map((l) => [l, { count: 0, spellings: 0 }]));
      for (const r of g.rows) { const l = statusLane(r.status); byLane[l].count += r.count; if (r.status && r.status.trim()) byLane[l].spellings += 1; }
      lanes = laneIds.map((l) => `${l} ${fmt(byLane[l].count)} (${byLane[l].spellings} spellings)`).join(' · ');
    } else {
      lanes = 'statusLane not loaded (tsx unavailable)';
    }
    laneText = `${fmt(total)} live rows, ${distinct} distinct raw spellings, ${fmt(blank)} blank/null, ${fmt(inVocab)} (${total ? Math.round((inVocab / total) * 100) : 0}%) already in vocabulary; lanes: ${lanes}`;
  }
  add('7', `${key}: allowed status values + per-lane counts`, verdict, `allowed (${allowed.length}): ${allowed.join(', ') || '—'}; ${laneText}`);
}

// --- render -----------------------------------------------------------------
const header = [
  `> Generated by \`node scripts/audit-crm-ux-reality.mjs\` — config from \`scripts/e2e/fixture-shapes.json\``,
  `> (captured ${snap._meta?.captured_at ?? '?'}), ${live.note}. Counts and config only; no record values, no PII.`,
  '',
  '| # | Precondition | Verdict | Prod value |',
  '|---|--------------|---------|------------|',
];
const body = rows.map((r) => `| ${r.n} | ${md(r.precondition)} | ${r.verdict} | ${md(r.value)} |`);
const fails = rows.filter((r) => r.verdict === 'FAIL');
const footer = ['', `Verdicts: ${rows.filter((r) => r.verdict === 'PASS').length} PASS · ${fails.length} FAIL · ${rows.filter((r) => r.verdict === 'INFO').length} INFO.${fails.length ? ` FAIL rows: ${fails.map((r) => `#${r.n} ${r.precondition}`).join('; ')}` : ''}`];
const table = [...header, ...body, ...footer].join('\n');
console.log(table);

if (WRITE) {
  let doc = readFileSync(DOC, 'utf8');
  const block = `${MARK_BEGIN}\n${table}\n${MARK_END}`;
  const b = doc.indexOf(MARK_BEGIN); const e = doc.indexOf(MARK_END);
  if (b !== -1 && e !== -1) {
    doc = doc.slice(0, b) + block + doc.slice(e + MARK_END.length);
  } else {
    const anchor = '\n## Local fixture';
    const i = doc.indexOf(anchor);
    const section = `\n## Prod reality (RO-1)\n\n${block}\n`;
    doc = i === -1 ? doc + section : doc.slice(0, i) + section + doc.slice(i);
  }
  writeFileSync(DOC, doc);
  console.error(`wrote RO-1 block into ${path.relative(REPO_ROOT, DOC)}`);
}
process.exit(0);
