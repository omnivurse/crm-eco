function walk(dir, out = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(p, out);
    else if (/\.(tsx|ts|jsx|js)$/.test(ent.name)) out.push(p);
  }
  return out;
}

function extractLucideImports(src) {
  const results = [];
  const re = /import\s*\{([^}]+)\}\s*from\s*['"]lucide-react['"]\s*;?/g;
  let m;
  while ((m = re.exec(src))) {
    const specs = [];
    let needsIconType = false;
    for (const part of m[1].split(',')) {
      let t = part.trim();
      if (!t) continue;
      // `type LucideIcon` or `LucideIcon` type-only
      if (/^(type\s+)?LucideIcon$/.test(t)) {
        needsIconType = true;
        continue;
      }
      t = t.replace(/^type\s+/, '');
      const [orig, alias] = t.split(/\s+as\s+/).map((s) => s.trim());
      if (orig === 'LucideIcon') {
        needsIconType = true;
        continue;
      }
      specs.push({ orig, local: alias || orig });
    }
    results.push({
      full: m[0],
      start: m.index,
      end: m.index + m[0].length,
      specs,
      needsIconType,
    });
  }
  return results;
}

function isClientFile(src) {
  return /^\s*['"]use client['"]\s*;?/m.test(src);
}

function addWeightProp(jsxTagContent) {
  // Already has weight=
  if (/\bweight\s*=/.test(jsxTagContent)) return jsxTagContent;
  // Self-closing or opening tag after component name — inject after name
  return jsxTagContent.replace(/^(\w+)/, '$1 weight="light"');
}

function transformFile(filePath) {
  let src = fs.readFileSync(filePath, 'utf8');
  const imports = extractLucideImports(src);
  if (!imports.length) return { changed: false };

  const renameLocal = new Map(); // local name → phosphor name (for JSX)
  const phosphorImports = new Map(); // phosphor export → local alias (if needed)
  const unmapped = new Set();
  let needsIconType = imports.some((i) => i.needsIconType);

  for (const imp of imports) {
    for (const { orig, local } of imp.specs) {
      const ph = MAP[orig];
      if (!ph) {
        unmapped.add(orig);
        continue;
      }
      if (local !== orig) {
        phosphorImports.set(ph, local);
        renameLocal.set(local, null);
      } else if (local === ph) {
        phosphorImports.set(ph, null);
      } else {
        phosphorImports.set(ph, null);
        if (local !== ph) renameLocal.set(local, ph);
      }
    }
  }

  if (unmapped.size) {
    return { changed: false, unmapped: [...unmapped], file: filePath };
  }

  const useSsr = !isClientFile(src);
  const importPath = useSsr
    ? '@phosphor-icons/react/dist/ssr'
    : '@phosphor-icons/react';

  const importNames = [...phosphorImports.entries()]
    .map(([ph, alias]) => (alias && alias !== ph ? `${ph} as ${alias}` : ph))
    .sort((a, b) => a.localeCompare(b));

  const newImport =
    importNames.length > 0
      ? `import { ${importNames.join(', ')} } from '${importPath}';`
      : '';
  const typeImport = needsIconType
    ? `import type { Icon as LucideIcon } from '@phosphor-icons/react';`
    : '';

  // Wipe lucide imports, then insert phosphor (+ optional type alias keeping LucideIcon name)
  let out = src.replace(/import\s*\{[^}]+\}\s*from\s*['"]lucide-react['"]\s*;?\s*\n?/g, '');

  const insertBlock = [typeImport, newImport].filter(Boolean).join('\n') + '\n';
  const useClient = out.match(/^(['"]use client['"];\s*\n)/);
  if (useClient) {
    out = out.replace(useClient[0], useClient[0] + insertBlock);
  } else {
    const firstImport = out.search(/^import\s/m);
    out =
      firstImport >= 0
        ? out.slice(0, firstImport) + insertBlock + out.slice(firstImport)
        : insertBlock + out;
  }

  // Rename JSX components: <Loader2 → <CircleNotch etc.
  for (const [from, to] of renameLocal) {
    if (!to) continue;
    const reOpen = new RegExp(`<${from}(\\s|>|/)`, 'g');
    const reClose = new RegExp(`</${from}>`, 'g');
    out = out.replace(reOpen, `<${to}$1`);
    out = out.replace(reClose, `</${to}>`);
    // typeof Icon references / icon: Loader2 in objects — rename identifiers carefully
    // Skip renaming when used as object keys or strings
    out = out.replace(new RegExp(`\\b${from}\\b`, 'g'), (match, offset) => {
      // Don't touch import line
      const lineStart = out.lastIndexOf('\n', offset) + 1;
      const line = out.slice(lineStart, out.indexOf('\n', offset));
      if (line.includes('from @phosphor') || line.includes("from '@phosphor") || line.includes('from "@phosphor')) {
        return match;
      }
      if (line.trimStart().startsWith('import ')) return match;
      return to;
    });
  }

  // Add weight="light" to Phosphor JSX usages for known icons
  const allPhNames = new Set([
    ...importNames.map((s) => s.split(/\s+as\s+/).pop().trim()),
    ...[...renameLocal.values()].filter(Boolean),
  ]);

  for (const name of allPhNames) {
    // Match <Name ...> or <Name ... />
    const re = new RegExp(`<${name}(\\s[^>]*?)(\\s*/)?>`, 'g');
    out = out.replace(re, (full, attrs = '', selfClose = '') => {
      if (/\bweight\s*=/.test(attrs)) return full;
      const trimmed = attrs.replace(/^\s*/, ' ');
      return `<${name} weight="light"${trimmed}${selfClose || ''}>`;
    });
    // <Name/> with no attrs
    out = out.replace(new RegExp(`<${name}\\s*/>`, 'g'), `<${name} weight="light" />`);
  }

  // Clean strokeWidth props (lucide-specific) — optional leave or strip
  out = out.replace(/\s+strokeWidth=\{[^}]+\}/g, '');
  out = out.replace(/\s+strokeWidth="[^"]*"/g, '');

  if (!DRY) fs.writeFileSync(filePath, out);
  return { changed: true, file: filePath, ssr: useSsr };
}

// --- main ---
const files = walk(ROOT).filter((f) => {
  const src = fs.readFileSync(f, 'utf8');
  return src.includes('lucide-react');
});

if (LIST_ONLY) {
  const names = new Set();
  for (const f of files) {
    for (const imp of extractLucideImports(fs.readFileSync(f, 'utf8'))) {
      for (const s of imp.specs) names.add(s.orig);
    }
  }
  console.log([...names].sort().join('\n'));
  console.log('TOTAL', names.size, 'in', files.length, 'files');
  process.exit(0);
}

const results = { changed: 0, skipped: 0, unmapped: new Map() };
for (const f of files) {
  const r = transformFile(f);
  if (r.unmapped?.length) {
    results.skipped++;
    for (const u of r.unmapped) {
      if (!results.unmapped.has(u)) results.unmapped.set(u, []);
      results.unmapped.get(u).push(path.relative(process.cwd(), f));
    }
    continue;
  }
  if (r.changed) results.changed++;
}

console.log(DRY ? '[DRY]' : '[DONE]', 'changed', results.changed, 'skipped', results.skipped);
if (results.unmapped.size) {
  console.log('\nUNMAPPED:');
  for (const [name, files] of [...results.unmapped.entries()].sort()) {
    console.log(`  ${name} (${files.length}) e.g. ${files[0]}`);
  }
  process.exitCode = 2;
}
