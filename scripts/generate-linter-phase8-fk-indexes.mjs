#!/usr/bin/env node
/**
 * Generate Phase 8a FK covering-index migration from Supabase performance linter JSON.
 *
 * Usage:
 *   node scripts/generate-linter-phase8-fk-indexes.mjs /path/to/advisors.json \
 *     > supabase/migrations/202606150001_linter_phase8a_fk_covering_indexes.sql
 *
 * Input: JSON array of linter results, or { lints: [...] } from get_advisors performance.
 * Resolves FK column ordinals against baseline CREATE TABLE column order.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const baselinePath = path.join(__dirname, '../supabase/migrations/00000000000000_baseline.sql');
const inputPath = process.argv[2];

if (!inputPath) {
  console.error('Usage: node scripts/generate-linter-phase8-fk-indexes.mjs <advisors.json>');
  process.exit(1);
}

const raw = JSON.parse(fs.readFileSync(inputPath, 'utf8'));
const lints = Array.isArray(raw) ? raw : raw.lints ?? [];
const fks = lints.filter((x) => x.name === 'unindexed_foreign_keys');

const baseline = fs.readFileSync(baselinePath, 'utf8');
const tableCols = new Map();
for (const m of baseline.matchAll(/CREATE TABLE ([\w.]+) \(([\s\S]*?)\n\);/g)) {
  const cols = [];
  for (const line of m[2].split('\n')) {
    const trimmed = line.trim().replace(/,$/, '');
    if (!trimmed || /^(CONSTRAINT|CHECK|PRIMARY KEY|UNIQUE|FOREIGN KEY)/.test(trimmed)) continue;
    const cm = trimmed.match(/^"?([\w]+)"?\s+/);
    if (cm) cols.push(cm[1]);
  }
  tableCols.set(m[1], cols);
}

const seenCols = new Set();
const seenNames = new Set();
const statements = [];

for (const x of fks) {
  const { schema, name: table, fkey_name: fkey, fkey_columns: ordinals } = x.metadata;
  const key = schema === 'public' ? `public.${table}` : `${schema}.${table}`;
  const cols = tableCols.get(key);
  if (!cols) {
    console.error(`// WARN: table not in baseline: ${key} (${fkey})`);
    continue;
  }
  const colNames = ordinals.map((n) => cols[n - 1]);
  const colKey = `${key}|${colNames.join(',')}`;
  if (seenCols.has(colKey)) continue;
  seenCols.add(colKey);

  let idxName = `idx_${table}_${colNames.join('_')}_fkey`;
  if (idxName.length > 63) idxName = idxName.slice(0, 63);
  const base = idxName;
  let i = 2;
  while (seenNames.has(idxName)) {
    idxName = `${base.slice(0, 58)}_${i}`.slice(0, 63);
    i += 1;
  }
  seenNames.add(idxName);

  statements.push(
    `CREATE INDEX IF NOT EXISTS ${idxName} ON ${schema}.${table} (${colNames.join(', ')}); -- ${fkey}`,
  );
}

console.log(`-- Phase 8a: Supabase linter — unindexed_foreign_keys (${statements.length} covering indexes)`);
console.log('-- Generated by scripts/generate-linter-phase8-fk-indexes.mjs');
console.log('-- Risk: LOW — additive indexes only');
console.log('');
console.log('BEGIN;');
console.log('');
console.log("SET lock_timeout = '5s';");
console.log('');
for (const s of statements) console.log(s);
console.log('');
console.log('COMMIT;');
console.log('');
console.log("NOTIFY pgrst, 'reload schema';");
